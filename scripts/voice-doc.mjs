// Список реплик ведущего для записи голоса: node scripts/voice-doc.mjs → docs/VOICE.md (из LINES в src/announcer.js)
import { writeFileSync } from 'fs';
import { allLines } from '../src/announcer.js';

const KIND = { start: 'Старт заезда', crash: 'Авария', lastLife: 'Осталась одна жизнь', nearMiss: 'Проскочил впритирку', nitro: 'Нитро',
    heart: 'Подобрал сердечко', fever: '«В ударе» (×5)', record: 'Новый рекорд в заезде', overtake: 'Обогнал соперника из таблицы',
    police: 'Началась погоня ГАИ', caught: 'ГАИ поймала', chance: 'Второй шанс', cassette: 'Видеокассета', billboard: 'Снёс рекламный щит',
    landscape: 'Пейзаж недели', finish: 'Итоги заезда', finishRecord: 'Итоги с рекордом' };

let s = `# Ведущий: реплики для записи голоса

Как записать и подключить:

1. Запиши каждую реплику отдельным файлом с именем из таблицы (например \`start_1.mp3\`). Моно, тишина в начале — не больше 0,1 с.
   Говори с азартом, как ведущий телешоу: громко, быстро, с улыбкой. Можно импровизировать — тогда поправь текст в таблице.
2. «Под 16 бит» (Audacity, бесплатно): «Трек → Частота» 16 000 Гц → «Эффекты → Компрессор» → по желанию «Bitcrusher»
   (8–10 бит, плагин) → «Экспорт» в mp3, 22 050 Гц, 64 кбит/с. Получится звук ведущего с приставки, и файлы маленькие.
3. Положи файлы в \`public/voice/\` и впиши их имена (без .mp3) в \`public/voice/index.json\`: \`["start_1", "crash_2"]\`.
   Чего нет в списке — ведущий говорит только текстом. Можно записывать по частям.
4. Новые реплики: строка в \`LINES\` (\`src/announcer.js\`), потом \`node scripts/voice-doc.mjs\` — таблица обновится (тест проверит).

В игре: «Настройки → 🎙 Ведущий» — голос и текст / только текст / молчит.

| Когда | Файл | Реплика |
|---|---|---|
`;
allLines().forEach(function(l) { s += '| ' + (KIND[l.kind] || l.kind) + ' | `' + l.id + '.mp3` | ' + l.text + ' |\n'; });
writeFileSync('docs/VOICE.md', s);
console.log('docs/VOICE.md — ' + allLines().length + ' реплик');
