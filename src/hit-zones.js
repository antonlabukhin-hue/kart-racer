/**
 * Зоны столкновения (бесконечная трасса): ошибка не решается одним пикселем.
 *   «лоб в лоб» — машина вошла в попутку или зверя ближе CORE_K от оси: авария, минус сердце;
 *   «задел боком» — краем (CORE_K..1 ширины столкновения): аварии нет, но скорость падает, множитель сгорает,
 *                   машину отталкивает в сторону; в правиле «ГАИ на хвосте» задел — погоня (как «споткнулся» в Subway Surfers),
 *                   задел ещё раз во время погони — уже авария.
 *   «на волоске» — прошёл рядом, не задев (src/near-miss.js).
 * Ямы, трубы, разломы, ремонт — всегда авария: их видно заранее и у каждой один ответ.
 * Логика — чистая (с тестами).
 */

export const CORE_K = 0.6;        // доля полуширины столкновения: ближе к оси — лоб в лоб
export const GRAZE_SPEED = 0.75;  // скорость после «задел»
export const GRAZE_PUSH = 0.6;    // толчок вбок (xVelocity), от помехи
export const GRAZE_STUN = 0.15;   // с без руля (у аварии — 0.4)

/** Тяжесть удара: dx — x игрока − x помехи, hw — полуширина столкновения; inf — бесконечная трасса (в кампании всё — авария) */
export function hitSeverity(dx, hw, inf) {
    if (!inf || !(hw > 0)) return 'major';
    return Math.abs(dx) < hw * CORE_K ? 'major' : 'minor';
}

/** В какую сторону оттолкнуть машину: от помехи (dx = 0 — вправо) */
export function grazePush(dx) {
    return (dx < 0 ? -1 : 1) * GRAZE_PUSH;
}

/**
 * Что делать с «задел»: chaseAll — правило «ГАИ на хвосте», chasing — погоня уже идёт.
 * 'graze' — только «задел»; 'chase' — «задел» и ГАИ садится на хвост; 'major' — это уже авария.
 */
export function grazeOutcome(chaseAll, chasing) {
    if (!chaseAll) return 'graze';
    return chasing ? 'major' : 'chase';
}
